CREATE OR REPLACE PACKAGE PKG_FARMTECH AS
    -- Insere uma leitura do sensor.
    -- Valida faixa, resolve o sensor pelo código e, abaixo do ideal da cultura,
    -- grava APLICACOES_INSUMOS com a mesma regra de src/crud_sensores.py.
    -- p_id_leitura recebe a chave gerada.
    -- Erros de aplicação: -20001 sensor, -20002 umidade, -20003 pH,
    -- -20004 NPK, -20005 bomba, -20006 temperatura, -20099 falha inesperada.
    PROCEDURE PRC_INSERIR_LEITURA (
        p_codigo_sensor      IN VARCHAR2,
        p_umidade_solo_pct   IN NUMBER,
        p_ph_solo            IN NUMBER,
        p_nitrogenio_mg_dm3  IN NUMBER,
        p_fosforo_mg_dm3     IN NUMBER,
        p_potassio_mg_dm3    IN NUMBER,
        p_temperatura_c      IN NUMBER,
        p_bomba_ligada       IN NUMBER DEFAULT NULL,
        p_data_hora          IN TIMESTAMP DEFAULT NULL,
        p_id_leitura         OUT NUMBER
    );

    -- Média de umidade_solo_pct do talhão, com duas casas.
    -- Talhão fora de TALHOES: erro -20010.
    FUNCTION FN_UMIDADE_MEDIA_TALHAO (
        p_codigo_talhao IN VARCHAR2
    ) RETURN NUMBER;
END PKG_FARMTECH;
/

CREATE OR REPLACE PACKAGE BODY PKG_FARMTECH AS
    PROCEDURE PRC_INSERIR_LEITURA (
        p_codigo_sensor      IN VARCHAR2,
        p_umidade_solo_pct   IN NUMBER,
        p_ph_solo            IN NUMBER,
        p_nitrogenio_mg_dm3  IN NUMBER,
        p_fosforo_mg_dm3     IN NUMBER,
        p_potassio_mg_dm3    IN NUMBER,
        p_temperatura_c      IN NUMBER,
        p_bomba_ligada       IN NUMBER DEFAULT NULL,
        p_data_hora          IN TIMESTAMP DEFAULT NULL,
        p_id_leitura         OUT NUMBER
    ) IS
        v_id_sensor       SENSORES.ID_SENSOR%TYPE;
        v_id_talhao       TALHOES.ID_TALHAO%TYPE;
        v_umid_min        CULTURAS.UMIDADE_IDEAL_MIN%TYPE;
        v_n_min           CULTURAS.N_MIN_MG_DM3%TYPE;
        v_p_min           CULTURAS.P_MIN_MG_DM3%TYPE;
        v_k_min           CULTURAS.K_MIN_MG_DM3%TYPE;
        v_bomba           LEITURAS_SENSORES.BOMBA_LIGADA%TYPE;
        v_data_hora       LEITURAS_SENSORES.DATA_HORA%TYPE;
        v_deficit_hidrico NUMBER(1);
        v_deficit_npk     NUMBER(1);
        v_agua_mm         APLICACOES_INSUMOS.VOLUME_AGUA_MM%TYPE;
        v_dose_npk        APLICACOES_INSUMOS.DOSE_NPK_KG_HA%TYPE;
        v_tipo            APLICACOES_INSUMOS.TIPO_APLICACAO%TYPE;
        v_motivo          APLICACOES_INSUMOS.MOTIVO_TECNICO%TYPE;
    BEGIN
        IF p_codigo_sensor IS NULL THEN
            RAISE_APPLICATION_ERROR(-20001, 'Sensor nao cadastrado.');
        END IF;

        IF p_umidade_solo_pct IS NULL
           OR p_umidade_solo_pct < 0
           OR p_umidade_solo_pct > 100 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Umidade do solo na faixa de 0 a 100.');
        END IF;

        IF p_ph_solo IS NULL OR p_ph_solo < 0 OR p_ph_solo > 14 THEN
            RAISE_APPLICATION_ERROR(-20003, 'pH do solo na faixa de 0 a 14.');
        END IF;

        IF p_nitrogenio_mg_dm3 IS NULL OR p_nitrogenio_mg_dm3 < 0
           OR p_fosforo_mg_dm3 IS NULL OR p_fosforo_mg_dm3 < 0
           OR p_potassio_mg_dm3 IS NULL OR p_potassio_mg_dm3 < 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'N, P e K a partir de zero.');
        END IF;

        IF p_temperatura_c IS NULL THEN
            RAISE_APPLICATION_ERROR(-20006, 'Temperatura obrigatoria.');
        END IF;

        IF p_bomba_ligada IS NOT NULL AND p_bomba_ligada NOT IN (0, 1) THEN
            RAISE_APPLICATION_ERROR(-20005, 'bomba_ligada aceita 0 ou 1.');
        END IF;

        BEGIN
            SELECT s.id_sensor,
                   s.id_talhao,
                   c.umidade_ideal_min,
                   c.n_min_mg_dm3,
                   c.p_min_mg_dm3,
                   c.k_min_mg_dm3
              INTO v_id_sensor,
                   v_id_talhao,
                   v_umid_min,
                   v_n_min,
                   v_p_min,
                   v_k_min
              FROM SENSORES s
              JOIN TALHOES t ON t.id_talhao = s.id_talhao
              JOIN CULTURAS c ON c.id_cultura = t.id_cultura
             WHERE s.codigo_sensor = p_codigo_sensor;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20001, 'Sensor nao cadastrado: ' || p_codigo_sensor);
        END;

        v_data_hora := NVL(p_data_hora, SYSTIMESTAMP);
        v_deficit_hidrico := CASE WHEN p_umidade_solo_pct < v_umid_min THEN 1 ELSE 0 END;
        v_deficit_npk := CASE
            WHEN p_nitrogenio_mg_dm3 < v_n_min
              OR p_fosforo_mg_dm3 < v_p_min
              OR p_potassio_mg_dm3 < v_k_min THEN 1
            ELSE 0
        END;

        IF p_bomba_ligada IS NULL THEN
            v_bomba := v_deficit_hidrico;
        ELSE
            v_bomba := p_bomba_ligada;
        END IF;

        INSERT INTO LEITURAS_SENSORES (
            id_sensor, data_hora, umidade_solo_pct, ph_solo,
            nitrogenio_mg_dm3, fosforo_mg_dm3, potassio_mg_dm3,
            temperatura_c, bomba_ligada
        ) VALUES (
            v_id_sensor, v_data_hora, p_umidade_solo_pct, p_ph_solo,
            p_nitrogenio_mg_dm3, p_fosforo_mg_dm3, p_potassio_mg_dm3,
            p_temperatura_c, v_bomba
        ) RETURNING id_leitura INTO p_id_leitura;

        IF v_deficit_hidrico = 1 OR v_deficit_npk = 1 THEN
            IF v_deficit_hidrico = 1 THEN
                v_agua_mm := ROUND(GREATEST(0, (v_umid_min + 8 - p_umidade_solo_pct) * 0.85), 2);
            ELSE
                v_agua_mm := 0;
            END IF;

            IF v_deficit_npk = 1 THEN
                v_dose_npk := ROUND(GREATEST(0, (v_n_min - p_nitrogenio_mg_dm3) * 1.8 + 15), 2);
            ELSE
                v_dose_npk := 0;
            END IF;

            IF v_deficit_hidrico = 1 AND v_deficit_npk = 1 THEN
                v_tipo := 'FERTIRRIGACAO';
            ELSIF v_deficit_hidrico = 1 THEN
                v_tipo := 'IRRIGACAO';
            ELSE
                v_tipo := 'ADUBACAO_NPK';
            END IF;

            v_motivo := 'Acionamento automatico via leitura #' || p_id_leitura
                        || ' (umidade=' || TO_CHAR(p_umidade_solo_pct)
                        || ', pH=' || TO_CHAR(p_ph_solo) || ')';

            INSERT INTO APLICACOES_INSUMOS (
                id_talhao, id_leitura_origem, data_aplicacao, tipo_aplicacao,
                volume_agua_mm, dose_npk_kg_ha, motivo_tecnico
            ) VALUES (
                v_id_talhao, p_id_leitura, v_data_hora, v_tipo,
                v_agua_mm, v_dose_npk, v_motivo
            );
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;
            RAISE_APPLICATION_ERROR(-20099, 'Falha ao inserir leitura: ' || SQLERRM);
    END PRC_INSERIR_LEITURA;

    FUNCTION FN_UMIDADE_MEDIA_TALHAO (
        p_codigo_talhao IN VARCHAR2
    ) RETURN NUMBER IS
        v_existe NUMBER;
        v_media  NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO v_existe
          FROM TALHOES
         WHERE codigo_talhao = p_codigo_talhao;

        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20010, 'Talhao nao cadastrado: ' || p_codigo_talhao);
        END IF;

        SELECT ROUND(AVG(l.umidade_solo_pct), 2)
          INTO v_media
          FROM TALHOES t
          LEFT JOIN SENSORES s ON s.id_talhao = t.id_talhao
          LEFT JOIN LEITURAS_SENSORES l ON l.id_sensor = s.id_sensor
         WHERE t.codigo_talhao = p_codigo_talhao;

        RETURN v_media;
    END FN_UMIDADE_MEDIA_TALHAO;
END PKG_FARMTECH;
/

CREATE OR REPLACE TRIGGER TRG_AUD_LEITURAS
    AFTER INSERT OR UPDATE OR DELETE ON LEITURAS_SENSORES
    FOR EACH ROW
DECLARE
    v_operacao AUDITORIA_LEITURAS.OPERACAO%TYPE;
    v_id       AUDITORIA_LEITURAS.ID_LEITURA%TYPE;
    v_detalhe  AUDITORIA_LEITURAS.DETALHE%TYPE;
BEGIN
    IF INSERTING THEN
        v_operacao := 'INSERT';
        v_id := :NEW.id_leitura;
        v_detalhe := 'umidade_solo_pct=' || TO_CHAR(:NEW.umidade_solo_pct)
                     || '; bomba_ligada=' || TO_CHAR(:NEW.bomba_ligada);
    ELSIF UPDATING THEN
        v_operacao := 'UPDATE';
        v_id := :NEW.id_leitura;
        v_detalhe := 'umidade_solo_pct ' || TO_CHAR(:OLD.umidade_solo_pct)
                     || ' -> ' || TO_CHAR(:NEW.umidade_solo_pct);
    ELSE
        v_operacao := 'DELETE';
        v_id := :OLD.id_leitura;
        v_detalhe := 'umidade_solo_pct=' || TO_CHAR(:OLD.umidade_solo_pct);
    END IF;

    INSERT INTO AUDITORIA_LEITURAS (id_leitura, operacao, usuario_banco, detalhe)
    VALUES (v_id, v_operacao, USER, v_detalhe);
END;
/

