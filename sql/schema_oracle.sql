CREATE TABLE CULTURAS (
    id_cultura          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cultura        VARCHAR2(60)  NOT NULL,
    variedade           VARCHAR2(80)  NOT NULL,
    umidade_ideal_min   NUMBER(5,2)   NOT NULL,
    umidade_ideal_max   NUMBER(5,2)   NOT NULL,
    ph_ideal_min        NUMBER(4,2)   NOT NULL,
    ph_ideal_max        NUMBER(4,2)   NOT NULL,
    n_min_mg_dm3        NUMBER(6,2)   NOT NULL,
    p_min_mg_dm3        NUMBER(6,2)   NOT NULL,
    k_min_mg_dm3        NUMBER(6,2)   NOT NULL
);

CREATE TABLE TALHOES (
    id_talhao           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cultura          NUMBER        NOT NULL,
    codigo_talhao       VARCHAR2(30)  NOT NULL UNIQUE,
    nome_talhao         VARCHAR2(80)  NOT NULL,
    area_ha             NUMBER(8,2)   NOT NULL,
    altitude_m          NUMBER(6,1)   NOT NULL,
    CONSTRAINT fk_talhoes_cultura FOREIGN KEY (id_cultura)
        REFERENCES CULTURAS (id_cultura)
);

CREATE TABLE SENSORES (
    id_sensor           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_talhao           NUMBER        NOT NULL,
    codigo_sensor       VARCHAR2(40)  NOT NULL UNIQUE,
    tipo_sensor         VARCHAR2(40)  NOT NULL,
    modelo_hw           VARCHAR2(60)  DEFAULT 'ESP32 + DHT22 + LDR + NPK' NOT NULL,
    status_operacional  VARCHAR2(20)  DEFAULT 'ATIVO' NOT NULL,
    CONSTRAINT fk_sensores_talhao FOREIGN KEY (id_talhao)
        REFERENCES TALHOES (id_talhao)
);

CREATE TABLE LEITURAS_SENSORES (
    id_leitura          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sensor           NUMBER        NOT NULL,
    data_hora           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    umidade_solo_pct    NUMBER(5,2)   NOT NULL,
    ph_solo             NUMBER(4,2)   NOT NULL,
    nitrogenio_mg_dm3   NUMBER(6,2)   NOT NULL,
    fosforo_mg_dm3      NUMBER(6,2)   NOT NULL,
    potassio_mg_dm3     NUMBER(6,2)   NOT NULL,
    temperatura_c       NUMBER(5,2)   NOT NULL,
    bomba_ligada        NUMBER(1)     DEFAULT 0 NOT NULL CHECK (bomba_ligada IN (0, 1)),
    CONSTRAINT fk_leituras_sensor FOREIGN KEY (id_sensor)
        REFERENCES SENSORES (id_sensor)
);

CREATE TABLE APLICACOES_INSUMOS (
    id_aplicacao        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_talhao           NUMBER        NOT NULL,
    id_leitura_origem   NUMBER,
    data_aplicacao      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    tipo_aplicacao      VARCHAR2(40)  NOT NULL,
    volume_agua_mm      NUMBER(6,2)   DEFAULT 0 NOT NULL,
    dose_npk_kg_ha      NUMBER(6,2)   DEFAULT 0 NOT NULL,
    motivo_tecnico      VARCHAR2(200) NOT NULL,
    CONSTRAINT fk_aplic_talhao FOREIGN KEY (id_talhao)
        REFERENCES TALHOES (id_talhao),
    CONSTRAINT fk_aplic_leitura FOREIGN KEY (id_leitura_origem)
        REFERENCES LEITURAS_SENSORES (id_leitura)
);
